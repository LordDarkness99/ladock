#!/usr/bin/env python3
"""
Generator konfigurasi Apache Gateway (vhost reverse-proxy) untuk mode Microservices.

Input  : daftar service dan path-prefix-nya via argumen.
Output : konten konfigurasi Apache (httpd) ke stdout, siap di-mount
         ke container Gateway.

Usage:
    python3 generate_gateway_conf.py \\
        --project my_project \\
        --services 'auth:8081,user:8082,order:8083'

Menghasilkan Apache VirtualHost yang:
  - Merutekan  /auth/*   -> http://app_auth:80/
  - Merutekan  /user/*   -> http://app_user:80/
  - Merutekan  /order/*  -> http://app_order:80/
"""

import argparse
import re
import sys


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _pairs(raw: str) -> dict[str, str]:
    result: dict[str, str] = {}
    if not raw.strip():
        return result
    for item in raw.split(","):
        item = item.strip()
        if ":" not in item:
            continue
        k, _, v = item.partition(":")
        result[k.strip()] = v.strip()
    return result


def _route_for_service(service: dict) -> str:
    route = str(service.get("route", service["name"])).strip("/")
    if not re.fullmatch(r"[A-Za-z0-9_-]+", route):
        raise ValueError(f"Route gateway tidak valid untuk service {service['name']!r}: {route!r}")
    return route


# ---------------------------------------------------------------------------
# Config builder
# ---------------------------------------------------------------------------

def build_gateway_conf(project: str, services: list[dict], gateway_port: int) -> str:
    """
    services: [{"name": str, "http_port": int}, ...]
    """
    lines: list[str] = [
        "# Apache API Gateway - Auto-generated by generate_gateway_conf.py",
        "# DO NOT EDIT manually — regenerated on every deploy",
        "",
        "LoadModule proxy_module modules/mod_proxy.so",
        "LoadModule proxy_http_module modules/mod_proxy_http.so",
        "LoadModule rewrite_module modules/mod_rewrite.so",
        "LoadModule headers_module modules/mod_headers.so",
        "",
        "<VirtualHost *:80>",
        f"    ServerName {project}.local",
        "",
        "    ProxyRequests Off",
        "    RedirectMatch 404 ^/$",
        "",
        "    # ── Security headers ────────────────────────────────────",
        '    Header always set X-Content-Type-Options "nosniff"',
        '    Header always set X-Frame-Options "SAMEORIGIN"',
        '    Header always set X-Gateway "apache-microservice-gw"',
        "",
        "    # ── Service routes (path-based, prefix stripped) ─────────",
    ]

    for svc in services:
        sname = svc["name"]
        route = _route_for_service(svc)
        container_port = svc.get("container_port", 80)
        lines += [
            f"",
            f"    # [{sname}] -> http://app_{sname}:{container_port}",
            f"    <Location /{route}/>",
            f"        ProxyPreserveHost On",
            f"        ProxyPassReverseCookiePath / /{route}/",
            f"    </Location>",
            f"    ProxyPass        /{route}/  http://app_{sname}:{container_port}/",
            f"    ProxyPassReverse /{route}/  http://app_{sname}:{container_port}/",
            f"    ProxyPassReverse /{route}/  http://app_{sname}/",
        ]

    lines += [
        "",
        "</VirtualHost>",
    ]
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--project",      required=True)
    ap.add_argument("--services",     required=True, help="'name1:port1,name2:port2,...'")
    ap.add_argument("--routes",       default="", help="'name1:path1,name2:path2,...'")
    ap.add_argument("--container-ports", default="", help="'name1:port1,name2:port2,...'")
    ap.add_argument("--gateway-port", required=True, type=int)
    args = ap.parse_args()

    svc_ports = _pairs(args.services)
    routes = _pairs(args.routes)
    container_ports = _pairs(args.container_ports)
    services = [
        {
            "name": n,
            "http_port": int(p),
            "route": routes.get(n, n),
            "container_port": int(container_ports.get(n, "80")),
        }
        for n, p in svc_ports.items()
    ]

    if not services:
        print("Tidak ada service.", file=sys.stderr)
        sys.exit(1)

    output = build_gateway_conf(args.project, services, args.gateway_port)
    sys.stdout.write(output)


if __name__ == "__main__":
    main()
